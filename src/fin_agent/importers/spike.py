"""Milestone 21 spike harness.

It runs a fresh parse run on the first statement for each bank, then reruns the submitted
parser on the rest, printing only pass/fail and counts. Real statements stay in a git-ignored
folder. The synthetic fixtures always run, so CI can prove the harness and the checks.
"""

from __future__ import annotations

import subprocess
import sys
import time
from dataclasses import dataclass, field
from pathlib import Path
from typing import Any

from fin_agent.importers.checks import account_check
from fin_agent.importers.helpers import HELPER_VERSION
from fin_agent.importers.monty import ScriptContext, normalize_accounts, run_script
from fin_agent.importers.periods import derive_period
from fin_agent.importers.readers import Doc, DocError, open_documents

BANKS = ("sbi", "union", "slice")
SYNTHETIC = {
    "sbi": ("sbi_csv", "SBI_PARSER", 24567890),
    "union": ("union_tsv", "UNION_PARSER", 10000000),
    "slice": ("slice_csv", "SLICE_PARSER", 100000),
}


@dataclass
class BankRun:
    bank: str
    status: str
    files: int = 0
    rows: int = 0
    verified: int = 0
    repairs: int = 0
    seconds: float = 0.0
    note: str | None = None


@dataclass
class SpikeReport:
    synthetic: list[BankRun] = field(default_factory=list)
    real: list[BankRun] = field(default_factory=list)
    real_root: str | None = None
    notes: list[str] = field(default_factory=list)

    def markdown(self) -> str:
        lines = [
            "# Milestone 21 spike results",
            "",
            "Generated by `fin-agent import-spike`. It prints counts and status words only; "
            "no narration, amount, balance, account number, password, or file name appears.",
            "",
            "## What can be verified now (synthetic fixtures)",
            "",
            "| Bank | Status | Rows | Verified files | Seconds |",
            "|---|---|---|---|---|",
        ]
        for run in self.synthetic:
            lines.append(
                f"| {run.bank} | {run.status} | {run.rows} | {run.verified}/{run.files} | "
                f"{run.seconds:.2f} |"
            )
        if self.real:
            lines += [
                "",
                "## Real statements",
                "",
                f"Folder: `{self.real_root}` (git-ignored)",
                "",
                "| Bank | Status | Files | Rows | Verified | Repairs | Seconds | Note |",
                "|---|---|---|---|---|---|---|---|",
            ]
            for run in self.real:
                lines.append(
                    f"| {run.bank} | {run.status} | {run.files} | {run.rows} | "
                    f"{run.verified}/{run.files} | {run.repairs} | {run.seconds:.2f} | "
                    f"{run.note or ''} |"
                )
        else:
            lines += [
                "",
                "## Real statements",
                "",
                "Not run: no real SBI, Union Bank, or Slice statements were provided. Put them "
                "in `private/statements/<bank>/` (git-ignored) and run `fin-agent import-spike`.",
                "Until then the decision for each bank stays open: the synthetic fixtures prove "
                "the reader, checks, and harness, not a real bank's layout. Milestone 24's "
                "12-month backfill and real-row baselines wait on the same files.",
            ]
        if self.notes:
            lines += ["", "## Notes", ""] + [f"- {note}" for note in self.notes]
        return "\n".join(lines) + "\n"


def run_synthetic() -> list[BankRun]:
    try:
        from tests import import_fixtures
    except ImportError:
        return []
    runs: list[BankRun] = []
    for bank, (payload_name, parser_name, opening) in SYNTHETIC.items():
        payload = getattr(import_fixtures, payload_name)()
        parser = getattr(import_fixtures, parser_name)
        doc = Doc(payload)
        period = derive_period(doc)
        started = time.perf_counter()
        result = __import__("asyncio").run(
            run_script(
                doc,
                parser,
                ScriptContext(
                    period=(period["start"], period["end"]) if period else None,
                    ledger_opening_paise=opening,
                    expected_fingerprint=None,
                    allow_vision=False,
                ),
            )
        )
        accounts, reason = normalize_accounts(result.output)
        if not accounts:
            runs.append(
                BankRun(
                    bank=bank,
                    status="FAILED",
                    files=1,
                    seconds=time.perf_counter() - started,
                    note=reason,
                )
            )
            continue
        check = account_check(
            accounts[0],
            period=(period["start"], period["end"]) if period else None,
            ledger_opening=opening,
        )
        runs.append(
            BankRun(
                bank=bank,
                status=check["status"],
                files=1,
                rows=len(accounts[0]["rows"]),
                verified=1 if check["status"] == "VERIFIED" else 0,
                seconds=time.perf_counter() - started,
            )
        )
    return runs


def _inside_repo(path: Path) -> bool:
    try:
        path.resolve().relative_to(Path.cwd().resolve())
        return True
    except ValueError:
        return False


def _is_ignored(path: Path) -> bool:
    try:
        result = subprocess.run(
            ["git", "check-ignore", "-q", str(path)],
            capture_output=True,
            timeout=10,
            check=False,
        )
        return result.returncode == 0
    except Exception:  # noqa: BLE001 - a missing git is not a reason to read files
        return False


def _files_for(root: Path, bank: str) -> list[Path]:
    folder = root / bank
    if folder.is_dir():
        return sorted(path for path in folder.iterdir() if path.is_file())
    return sorted(path for path in root.glob(f"*{bank}*") if path.is_file())


def run_real(
    root: Path,
    *,
    model: Any = None,
    password: str | None = None,
    bank: str | None = None,
    max_files: int = 12,
    ledger_opening_paise: int | None = None,
) -> tuple[list[BankRun], list[str]]:
    import asyncio

    notes: list[str] = []
    if not root.is_dir():
        return [], [f"No folder at {root}."]
    if _inside_repo(root) and not _is_ignored(root):
        return [], ["Refusing to read a statement folder that git does not ignore."]
    runs: list[BankRun] = []
    banks = [bank] if bank else list(BANKS)
    for name in banks:
        files = _files_for(root, name)[:max_files]
        if not files:
            runs.append(BankRun(bank=name, status="not provided", note="no files"))
            continue
        started = time.perf_counter()
        try:
            open_documents(files[0].read_bytes(), password=password)
        except DocError as exc:
            runs.append(BankRun(bank=name, status="host error", files=1, note=exc.code))
            continue
        except Exception as exc:  # noqa: BLE001 - the spike reports, it does not crash
            runs.append(BankRun(bank=name, status="host error", files=1, note=type(exc).__name__))
            continue
        parsed = asyncio.run(
            _parse_first(
                files[0].read_bytes(),
                model=model,
                password=password,
                opening=ledger_opening_paise,
            )
        )
        if parsed is None or not parsed["script"]:
            runs.append(
                BankRun(
                    bank=name,
                    status=(parsed or {}).get("status", "failed"),
                    files=len(files),
                    seconds=time.perf_counter() - started,
                    note=(parsed or {}).get("reason") or "no parser",
                )
            )
            continue
        script = parsed["script"]
        verified = 1 if parsed["status"] == "review" else 0
        rows = int(parsed["rows"])
        for path in files[1:]:
            try:
                other = open_documents(path.read_bytes(), password=password)[0]
            except Exception:  # noqa: BLE001 - one bad member does not stop the spike
                continue
            other_period = derive_period(other)
            replay = __import__("asyncio").run(
                run_script(
                    other,
                    script,
                    ScriptContext(
                        period=(other_period["start"], other_period["end"])
                        if other_period
                        else None,
                        ledger_opening_paise=ledger_opening_paise,
                        allow_vision=True,
                    ),
                )
            )
            accounts, _reason = normalize_accounts(replay.output)
            if not accounts:
                continue
            rows += sum(len(account["rows"]) for account in accounts)
            check = account_check(
                accounts[0],
                period=(other_period["start"], other_period["end"]) if other_period else None,
                ledger_opening=ledger_opening_paise,
            )
            verified += 1 if check["status"] == "VERIFIED" else 0
        runs.append(
            BankRun(
                bank=name,
                status="parser_submitted" if parsed["status"] == "review" else "checks failed",
                files=len(files),
                rows=rows,
                verified=verified,
                repairs=0,
                seconds=time.perf_counter() - started,
            )
        )
    notes.append("xfina compared: not installed; OCR comparison: not run (no OCR package).")
    notes.append(f"Helper version used by the harness: {HELPER_VERSION}.")
    return runs, notes


async def _parse_first(
    payload: bytes,
    *,
    model: Any,
    password: str | None,
    opening: int | None,
) -> dict[str, Any] | None:
    """Run one fresh parser task through the real parser subagent and read its import."""
    import hashlib

    from fin_agent.agent.deps import AgentDeps
    from fin_agent.agent.parser import build_parser_agent
    from fin_agent.db.conn import connect
    from fin_agent.importers.pipeline import create_import
    from fin_agent.ledger.audit import new_id

    async with connect() as conn:
        attachment_id = await new_id(conn, "att")
        await conn.execute(
            """
            INSERT INTO attachments (id, kind, filename, content_type, size_bytes, sha256, data)
            VALUES ($1, 'statement', 'spike-statement', 'application/octet-stream', $2, $3, $4)
            """,
            attachment_id,
            len(payload),
            hashlib.sha256(payload).hexdigest(),
            payload,
        )
        row = await create_import(conn, attachment_id=attachment_id)
        if opening is not None:
            await conn.execute(
                "UPDATE imports SET review = jsonb_build_object('manual_opening_paise', $1) "
                "WHERE id = $2",
                opening,
                row["id"],
            )
    agent = build_parser_agent(model)
    try:
        await agent.run(
            f"Parse the attached statement. Attachment IDs: {attachment_id}",
            deps=AgentDeps(conversation_id="spike"),
        )
    except Exception:  # noqa: BLE001 - the spike reports, it does not crash
        pass
    async with connect() as conn:
        current = await conn.fetchrow("SELECT * FROM imports WHERE id = $1", row["id"])
        lines = await conn.fetchval(
            "SELECT count(*) FROM statement_lines WHERE import_id = $1", row["id"]
        )
    if current is None:
        return None
    return {
        "status": current["status"],
        "reason": current["reason"],
        "script": current["parser"],
        "rows": int(lines or 0),
    }


def check_real_command(
    file: Path, parser: Path, *, opening: int | None, period: tuple[str, str] | None
) -> str:
    """Run the research harness on one synthetic file, printing only its verdict."""
    command = [
        sys.executable,
        str(Path("docs/research/monty-document-parsing/check_real.py").resolve()),
        str(file),
        "--parser",
        str(parser),
    ]
    if opening is not None:
        command += ["--ledger-opening", str(opening)]
    if period:
        command += ["--period", *period]
    result = subprocess.run(command, capture_output=True, text=True, timeout=120, check=False)
    return result.stdout.strip().splitlines()[-1] if result.stdout.strip() else "no output"


